export function parseData() {
  const data: EclipseProfile[] = [];

  RAW_SOLAR_DATA.split("\n").forEach(line => {
    if (line === "") {
      return;
    }

    const nasaCatalogNumber = parseInt(line.slice(0, 5));

    const months: Record<string, string> = {
      Jan: "01", Feb: "02", Mar: "03", Apr: "04", May: "05", Jun: "06",
      Jul: "07", Aug: "08", Sep: "09", Oct: "10", Nov: "11", Dec: "12"
    };

    const dateRaw = line.slice(7, 18);

    const year = dateRaw.slice(0, 4);
    const month = months[dateRaw.slice(5, 8)];
    const day = dateRaw.slice(9, 11);

    const time = line.slice(20, 28);

    const datetime = new Date(`${year}-${month}-${day}T${time}Z`);

    const types: Record<string, EclipseType> = {
      P: EclipseType.SolarPartial,
      A: EclipseType.SolarAnnular,
      T: EclipseType.SolarTotal,
      H: EclipseType.SolarHybrid,
    }

    const type = types[line.slice(50, 51)];

    data.push({
      nasaCatalogNumber,
      datetime,
      type,
      durationSeconds: parseSolarDuration(line.slice(94, 100)),
    })
  });

  RAW_LUNAR_DATA.split("\n").forEach(line => {
    const trimmed = line.trim();

    if (trimmed === "") {
      return;
    }

    const parts = trimmed.split(/\s+/);
    const months: Record<string, string> = {
      Jan: "01", Feb: "02", Mar: "03", Apr: "04", May: "05", Jun: "06",
      Jul: "07", Aug: "08", Sep: "09", Oct: "10", Nov: "11", Dec: "12"
    };

    const nasaCatalogNumber = parseInt(parts[0], 10);
    const year = parts[1];
    const month = months[parts[2]];
    const day = parts[3];
    const time = parts[4];
    const datetime = new Date(`${year}-${month}-${day}T${time}Z`);

    const eclipseType = parts[8];
    const type = eclipseType.startsWith("P")
      ? EclipseType.LunarPartial
      : eclipseType.startsWith("T")
        ? EclipseType.LunarTotal
        : EclipseType.LunarPenumbral;

    // Columns 13/14/15 are the penumbral, partial and total durations. Report
    // the deepest phase this eclipse reaches, since the shallower ones are
    // always present and would make every event look alike.
    const durationSeconds =
      type === EclipseType.LunarTotal
        ? parseLunarMinutes(parts[15])
        : type === EclipseType.LunarPartial
          ? parseLunarMinutes(parts[14])
          : parseLunarMinutes(parts[13]);

    data.push({
      nasaCatalogNumber,
      datetime,
      type,
      durationSeconds,
    });
  });

  data.sort((a, b) => a.datetime.getTime() - b.datetime.getTime());

  return data;
}
